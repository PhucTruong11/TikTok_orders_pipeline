    contains(cast(order_sn as varchar), '*') as is_order_id_masked,

    cast(pkId as varchar) as pk_id,
    cast(user_id as varchar) as user_id,
    cast(shop_id as varchar) as shop_id,
    cast(order_sn as varchar) as order_id,
    cast(order_status as varchar) as raw_order_status,
    {{ normalize_order_status('order_status') }} as order_status,
    cast(order_status_raw as varchar) as source_order_status_raw,
    {{ clean_string('shop_name') }} as shop_name,
    upper(trim(cast(currency as varchar))) as currency,
    cast(create_time as timestamp) as created_time,
    cast(pay_time as timestamp) as paid_time,
    cast(shipped_time as timestamp) as shipped_time,
    cast(completed_time as timestamp) as completed_time,
    cast(cancel_time as timestamp) as cancelled_time,
    cast(update_time as timestamp) as updated_time,
    cast(synced_at as timestamp) as synced_updated_at,
    cast(ship_by_date as timestamp) as ship_by_date,
    cast(estimated_shipping_date as timestamp) as estimated_shipping_date,
    cast(null as timestamp) as delivered_time,
    cast(null as timestamp) as delivery_sla_time,
    cast(item_id as varchar) as product_id,
    cast(model_id as varchar) as sku_id,
    {{ clean_string('item_name') }} as product_name,
    {{ clean_string('model_name') }} as sku_name,
    cast(item_sku as varchar) as item_sku,
    cast(model_sku as varchar) as model_sku,
    cast(quantity as integer) as quantity,
    cast(original_price as decimal(18,2)) as item_original_price,
    cast(model_discounted_price as decimal(18,2)) as item_sale_price,
    cast(item_weight as decimal(18,4)) as item_weight,
    cast(total_order_value as decimal(18,2)) as total_order_value,
    cast(buyer_total_amount as decimal(18,2)) as buyer_total_amount,
    cast(seller_discount as decimal(18,2)) as seller_discount,
    cast(shopee_discount as decimal(18,2)) as shopee_discount,
    cast(voucher_from_seller as decimal(18,2)) as voucher_from_seller,
    cast(voucher_from_shopee as decimal(18,2)) as voucher_from_shopee,
    cast(commission_fee as decimal(18,2)) as commission_fee,
    cast(service_fee as decimal(18,2)) as service_fee,
    cast(transaction_fee as decimal(18,2)) as transaction_fee,
    cast(escrow_amount as decimal(18,2)) as escrow_amount,
    cast(actual_shipping_fee as decimal(18,2)) as actual_shipping_fee,
    cast(estimated_shipping_fee as decimal(18,2)) as estimated_shipping_fee,
    cast(return_shipping_fee as decimal(18,2)) as return_shipping_fee,
    cast(returned_quantity as integer) as returned_quantity,
